"""Standalone portal-return experiment. Never carves terrain or starts FlusGrid jobs."""
from pathlib import Path
import json,zipfile,shutil
ROOT=Path(__file__).resolve().parents[1]
PACK=ROOT/'portal-test'
DIMS=[('overworld',1),('the_nether',2),('the_end',3)]
OBJECTIVES=['fpt_prev','fpt_dim','fpt_valid','fpt_sd','fpt_x','fpt_y','fpt_z','fpt_yaw','fpt_pitch','fpt_dx','fpt_dy','fpt_dz','fpt_dd','fpt_allow','fpt_notice','fpt_blocks','fpt_seen','fpt_epoch','fpt_last','fpt_tick','fpt_mount']
def write(p,s):
 p=PACK/p;p.parent.mkdir(parents=True,exist_ok=True);p.write_text(s.rstrip()+'\n')
def f(n,ls):write(Path('data/fg_portal_test/function')/(n+'.mcfunction'),'\n'.join(ls))
def build():
 if PACK.exists():shutil.rmtree(PACK)
 write(Path('pack.mcmeta'),json.dumps({'pack':{'description':'FlusGrid portal return TEST 0.1 — no terrain conversion','min_format':[121,0],'max_format':[121,0]}}))
 for kind in ['load','tick']:write(Path(f'data/minecraft/tags/function/{kind}.json'),json.dumps({'values':['fg_portal_test:'+kind]}))
 write(Path('data/fg_portal_test/tags/block/safe_floor.json'),json.dumps({'values':['minecraft:stone','minecraft:cobblestone','minecraft:obsidian','minecraft:crying_obsidian','minecraft:grass_block','minecraft:dirt','minecraft:netherrack','minecraft:end_stone','minecraft:deepslate','minecraft:cobbled_deepslate','minecraft:bedrock','#minecraft:planks']}))
 f('load',[*[f'scoreboard objectives add {o} dummy' for o in OBJECTIVES],'scoreboard objectives add fpt_deaths deathCount','scoreboard players add #epoch fpt_tick 1','scoreboard players set #clock fpt_tick 0'])
 f('dimension',['scoreboard players set @s fpt_dim 0',*[f'execute if dimension minecraft:{d} run scoreboard players set @s fpt_dim {i}' for d,i in DIMS]])
 # Deliberately conservative open-space checkpoint, on a full-block whitelist.
 safe=['scoreboard players set #safe fpt_tick 1','execute unless block ~ ~-1 ~ #fg_portal_test:safe_floor run scoreboard players set #safe fpt_tick 0']
 for x in range(-1,2):
  for z in range(-1,2):
   for y in [0,1]:safe.append(f'execute unless block ~{x} ~{y} ~{z} minecraft:air run scoreboard players set #safe fpt_tick 0')
 for x in range(-2,3):
  for z in range(-2,3):
   for y in [-1,0,1]:
    for block in ['nether_portal','end_portal','end_gateway']:
     safe.append(f'execute if block ~{x} ~{y} ~{z} minecraft:{block} run scoreboard players set #safe fpt_tick 0')
 f('safe',safe)
 f('save',[
  *[f'execute store result score @s fpt_{a} run data get entity @s Pos[{i}] 16' for a,i in [('x',0),('y',1),('z',2)]],
  *[f'execute store result score @s fpt_{a} run data get entity @s Rotation[{i}] 1000' for a,i in [('yaw',0),('pitch',1)]],
  'scoreboard players operation @s fpt_sd = @s fpt_dim','scoreboard players set @s fpt_valid 1',
 ])
 f('arm',[
  'execute unless entity @s[type=minecraft:player] run return 0','function fg_portal_test:dimension',
  'execute if score @s fpt_dim matches 0 run return 0',
  'execute store success score @s fpt_mount on vehicle if entity @s',
  'execute if score @s fpt_mount matches 1 run return run tellraw @s {text:"Test on foot. Dismount first.",color:"red"}',
  'function fg_portal_test:safe',
  'execute unless score #safe fpt_tick matches 1 run return run tellraw @s {text:"Stand on flat stone/obsidian with open space around you, at least 3 blocks from the portal. Then arm again.",color:"yellow"}',
  'function fg_portal_test:save','scoreboard players operation @s fpt_prev = @s fpt_dim',
  'scoreboard players set @s fpt_allow 0','scoreboard players set @s fpt_notice 0','scoreboard players set @s fpt_blocks 0',
  'scoreboard players set @s fpt_seen 0','execute if score @s fpt_deaths matches 0.. run scoreboard players operation @s fpt_seen = @s fpt_deaths',
  'scoreboard players operation @s fpt_epoch = #epoch fpt_tick','scoreboard players operation @s fpt_last = #clock fpt_tick',
  'tag @s add fpt_enabled',
  'tellraw @s {text:"PORTAL TEST ARMED. Walk into a portal. The destination will be rejected and you should return to your approach point. No terrain is generated by this test.",color:"yellow"}',
 ])
 f('off',['tag @s remove fpt_enabled','scoreboard players set @s fpt_notice 0','tellraw @s {text:"Portal test disabled for you.",color:"green"}'])
 f('allow_next',['execute unless entity @s[tag=fpt_enabled] run return run tellraw @s {text:"Arm the test first.",color:"yellow"}','scoreboard players set @s fpt_allow 1','tellraw @s {text:"TEST: Your next dimension change is allowed. This simulates a ready destination; nothing has been gridded.",color:"green"}'])
 f('tick',['scoreboard players add #clock fpt_tick 1','scoreboard players operation #previous fpt_tick = #clock fpt_tick','scoreboard players remove #previous fpt_tick 1','execute as @a[tag=fpt_enabled] at @s run function fg_portal_test:player'])
 f('player',[
  'execute unless score @s fpt_epoch = #epoch fpt_tick run return run function fg_portal_test:stale',
  'execute unless score @s fpt_last = #previous fpt_tick run return run function fg_portal_test:stale',
  'scoreboard players operation @s fpt_last = #clock fpt_tick',
  'execute if score @s fpt_deaths > @s fpt_seen run return run function fg_portal_test:stale',
  'function fg_portal_test:dimension',
  'execute unless score @s fpt_dim = @s fpt_prev run return run function fg_portal_test:transition',
  'execute if score @s fpt_notice matches 1.. run title @s actionbar {text:"TEST: Destination not ready. Returned to your portal approach; no generation is running.",color:"yellow"}',
  'execute if score @s fpt_notice matches 1.. run scoreboard players remove @s fpt_notice 1',
  'execute store success score @s fpt_mount on vehicle if entity @s',
  'execute if score @s fpt_mount matches 1 run return 0',
  'function fg_portal_test:safe','execute if score #safe fpt_tick matches 1 run function fg_portal_test:save',
 ])
 f('stale',['tag @s remove fpt_enabled','tellraw @s {text:"Portal test disarmed after reload, reconnect or death. Stand safely outside a portal and arm again.",color:"yellow"}'])
 f('transition',[
  'scoreboard players operation @s fpt_dd = @s fpt_dim',
  *[f'execute store result score @s fpt_d{a} run data get entity @s Pos[{i}] 16' for a,i in [('x',0),('y',1),('z',2)]],
  'execute if score @s fpt_allow matches 1 run return run function fg_portal_test:accept',
  'execute unless score @s fpt_valid matches 1 run return run function fg_portal_test:failed',
  'execute unless score @s fpt_sd = @s fpt_prev run return run function fg_portal_test:failed',
  'execute store success score @s fpt_mount on vehicle if entity @s',
  'execute if score @s fpt_mount matches 1 run return run function fg_portal_test:failed',
  *[f'execute store result storage fg_portal_test:work return.{a} double 0.0625 run scoreboard players get @s fpt_{a}' for a in 'xyz'],
  *[f'execute store result storage fg_portal_test:work return.{a} double 0.001 run scoreboard players get @s fpt_{a}' for a in ['yaw','pitch']],
  *[f'execute if score @s fpt_sd matches {i} in minecraft:{d} run return run function fg_portal_test:return with storage fg_portal_test:work return' for d,i in DIMS],
  'function fg_portal_test:failed',
 ])
 f('return',[
  '$execute positioned $(x) $(y) $(z) unless loaded ~ ~ ~ run return run function fg_portal_test:failed',
  '$execute positioned $(x) $(y) $(z) run function fg_portal_test:safe',
  'execute unless score #safe fpt_tick matches 1 run return run function fg_portal_test:failed',
  '$execute store success score #returned fpt_tick run tp @s $(x) $(y) $(z) $(yaw) $(pitch)',
  'execute unless score #returned fpt_tick matches 1 run return run function fg_portal_test:failed',
  'scoreboard players operation @s fpt_prev = @s fpt_sd',
  'scoreboard players add @s fpt_blocks 1','scoreboard players set @s fpt_notice 100',
  'title @s times 5 60 10','title @s title {text:"Destination not ready",color:"yellow"}',
  'title @s subtitle {text:"TEST: Returned to your portal approach",color:"white"}',
  'tellraw @s {text:"TEST RETURN: source checkpoint restored. The destination coordinates were recorded; no gridding was queued.",color:"yellow"}',
 ])
 f('accept',['scoreboard players set @s fpt_allow 0','scoreboard players set @s fpt_notice 0','scoreboard players operation @s fpt_prev = @s fpt_dim','scoreboard players set @s fpt_valid 0','tellraw @s {text:"TEST: Destination accepted. Step away from the portal onto an open solid floor to record a new return point.",color:"green"}'])
 f('failed',['tag @s remove fpt_enabled','tellraw @s {text:"TEST RETURN FAILED: no valid loaded departure checkpoint, blocked checkpoint, unsupported dimension, or mounted transit. Test disabled; you were NOT sent to spawn. Report this result.",color:"red"}'])
 f('status',['tellraw @s [{text:"Portal test: armed="},{selector:"@s[tag=fpt_enabled]"},{text:" | returns="},{score:{name:"@s",objective:"fpt_blocks"}},{text:" | source dimension="},{score:{name:"@s",objective:"fpt_sd"}},{text:" | last destination dimension="},{score:{name:"@s",objective:"fpt_dd"}},{text:" | destination XYZ (divide by16): "},{score:{name:"@s",objective:"fpt_dx"}},{text:", "},{score:{name:"@s",objective:"fpt_dy"}},{text:", "},{score:{name:"@s",objective:"fpt_dz"}}]'])
 out=ROOT/'dist/FlusGrid-portal-return-test-0.1.zip'
 with zipfile.ZipFile(out,'w',zipfile.ZIP_DEFLATED) as z:
  for p in sorted(PACK.rglob('*')):
   if p.is_file():z.write(p,p.relative_to(PACK))
 print(out)
if __name__=='__main__':build()
